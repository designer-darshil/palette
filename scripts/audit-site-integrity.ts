assert(routesToVerify.length === 29, `All 29 core application routes mapped and present in route table`);

// Verify sample navigation slugs
const sampleSlug = CURATED_PALETTES[0]?.slug || 'after-hours';
const found = CURATED_PALETTES.find((p) => p.slug === sampleSlug);
assert(found !== undefined && found.title.length > 0, `Route param lookup for slug "${sampleSlug}" returns valid palette (${found?.title})`);

